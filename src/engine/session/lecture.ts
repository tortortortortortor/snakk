const WORDS_PER_SECOND = 3.1;

function build(): SessionFile['events'] {
  const events: SessionFile['events'] = [];
  let t = 0;
  LINES.forEach((text, i) => {
    const words = text.split(/\s+/).length;
    const dur = Math.round((words / WORDS_PER_SECOND) * 1000);
    events.push({ t, type: 'speechStart' });
    events.push({ t: t + dur, type: 'speechEnd' });
    events.push({
      t: t + dur + 500,
      type: 'final',
      forced: true,
      segment: { id: `lec${i}`, text, lang: 'en', startMs: t, endMs: t + dur, latencyMs: 0 },
    });
    // Pauses vary a little, like real speech.
    t += dur + 1000 + ((i * 7919) % 5) * 250;
  });
  return events;
}

